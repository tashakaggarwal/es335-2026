def build_site_player_data(raw_dir: str):
    """Delegate to ipl_winprob.parse.build_serving_player_profiles for zero training-serving skew."""
    import sys
    from pathlib import Path

    root = Path(__file__).resolve().parent.parent
    src_path = str(root / "src")
    if src_path not in sys.path:
        sys.path.insert(0, src_path)
    from ipl_winprob.parse import build_serving_player_profiles

    return build_serving_player_profiles(Path(raw_dir), full_name_map=PLAYER_FULL_NAMES)


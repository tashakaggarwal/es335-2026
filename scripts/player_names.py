def get_full_name(short_name: str) -> str:
    return PLAYER_FULL_NAMES.get(short_name, short_name)


TEAM_MAP = {
    "Delhi Daredevils": "Delhi Capitals",
    "Kings XI Punjab": "Punjab Kings",
    "Royal Challengers Bangalore": "Royal Challengers Bengaluru",
    "Rising Pune Supergiants": "Rising Pune Supergiant",
}

NON_BOWLER_WKTS = {
    "run out", "retired hurt", "retired out",
    "obstructing the field", "handled the ball", "timed out",
}


def build_site_player_data(raw_dir: str):
    import json
    from collections import defaultdict
    from pathlib import Path

    bat_runs = defaultdict(int)
    bat_balls = defaultdict(int)
    bat_outs = defaultdict(int)
    bowl_runs = defaultdict(int)
    bowl_balls = defaultdict(int)
    bowl_wkts = defaultdict(int)

    team_app_25_26 = defaultdict(lambda: defaultdict(int))
    team_bat_pos = defaultdict(lambda: defaultdict(list))
    team_bowl_app = defaultdict(lambda: defaultdict(int))

    files = sorted(Path(raw_dir).glob("*.json"))
    for fp in files:
        with fp.open(encoding="utf-8") as f:
            data = json.load(f)
        info = data.get("info", {})
        event_name = (info.get("event") or {}).get("name", "")
        if "Indian Premier League" not in event_name and info.get("competition") != "IPL":
            continue
        dates = info.get("dates") or []
        if not dates:
            continue
        season = int(str(dates[0])[:4])

        players_by_team = info.get("players") or {}
        if season >= 2025:
            for raw_t, plist in players_by_team.items():
                t = TEAM_MAP.get(raw_t, raw_t)
                for p in plist:
                    fn = get_full_name(p)
                    team_app_25_26[t][fn] += 1

        for inn in data.get("innings", []):
            if inn.get("super_over"):
                continue
            raw_bt = inn.get("team", "")
            bt = TEAM_MAP.get(raw_bt, raw_bt)
            # Determine bowling team
            all_teams = [TEAM_MAP.get(rt, rt) for rt in (info.get("teams") or [])]
            bw_team = next((t for t in all_teams if t != bt), "")
            bowlers_in_inn = set()
            seen_batters = []
            for ov in inn.get("overs", []):
                for d in ov.get("deliveries", []):
                    batter = get_full_name(d.get("batter", ""))
                    non_st = get_full_name(d.get("non_striker", ""))
                    bowler = get_full_name(d.get("bowler", ""))
                    if batter and batter not in seen_batters:
                        seen_batters.append(batter)
                    if non_st and non_st not in seen_batters:
                        seen_batters.append(non_st)
                    if bowler:
                        bowlers_in_inn.add(bowler)
                    extras = d.get("extras") or {}
                    wides = extras.get("wides", 0)
                    noballs = extras.get("noballs", 0)
                    byes = extras.get("byes", 0)
                    legbyes = extras.get("legbyes", 0)
                    runs_bat = (d.get("runs") or {}).get("batter", 0)
                    runs_total = (d.get("runs") or {}).get("total", 0)

                    if wides == 0 and batter:
                        bat_balls[batter] += 1
                        bat_runs[batter] += runs_bat
                    if wides == 0 and noballs == 0 and bowler:
                        bowl_balls[bowler] += 1
                    if bowler:
                        bowl_runs[bowler] += (runs_total - byes - legbyes)

                    for w in d.get("wickets") or []:
                        kind = w.get("kind", "")
                        p_out = get_full_name(w.get("player_out", ""))
                        if kind != "retired hurt" and p_out:
                            bat_outs[p_out] += 1
                        if kind and kind not in NON_BOWLER_WKTS and bowler:
                            bowl_wkts[bowler] += 1

            if season >= 2025:
                for pos_idx, b_fn in enumerate(seen_batters):
                    team_bat_pos[bt][b_fn].append(pos_idx + 1)
                if bw_team:
                    for b_fn in bowlers_in_inn:
                        team_bowl_app[bw_team][b_fn] += 1

    all_players = sorted(set(bat_balls.keys()) | set(bowl_balls.keys()) | {
        p for t_dict in team_app_25_26.values() for p in t_dict.keys()
    })

    batters_sr = {}
    batters_bpd = {}
    batters_avg = {}
    bowlers_econ = {}
    bowlers_wkt = {}
    bowlers_balls_map = {}

    for p in all_players:
        bb = bat_balls[p]
        br = bat_runs[p]
        bo = bat_outs[p]
        sr = (br + 60.0 * 1.25) / (bb + 60.0) * 100.0
        bpd = (bb + 60.0) / (bo + (60.0 / 18.0))
        avg = (sr * bpd) / 100.0
        batters_sr[p] = round(float(sr), 2)
        batters_bpd[p] = round(float(bpd), 2)
        batters_avg[p] = round(float(avg), 2)

        wb = bowl_balls[p]
        wr = bowl_runs[p]
        ww = bowl_wkts[p]
        econ = ((wr + 120.0 * (8.3 / 6.0)) / (wb + 120.0)) * 6.0
        wkt_r = (ww + 120.0 * 0.052) / (wb + 120.0)
        bowlers_econ[p] = round(float(econ), 2)
        bowlers_wkt[p] = round(float(wkt_r), 5)
        bowlers_balls_map[p] = int(wb)

    team_squads = {}
    rosters = {}
    bowl_rosters = {}
    for t, app_dict in sorted(team_app_25_26.items()):
        def _mean_pos(p):
            pos_list = team_bat_pos[t][p]
            return sum(pos_list) / len(pos_list) if pos_list else 10.5
        # Sort full squad by appearances desc, then mean batting position asc
        squad_sorted = sorted(
            app_dict.keys(),
            key=lambda p: (-app_dict[p], _mean_pos(p), p),
        )
        team_squads[t] = squad_sorted
        # Default 12 for batting XI: top 12 by appearances, ordered by mean batting position
        top12_bat = sorted(
            squad_sorted[:12],
            key=lambda p: (_mean_pos(p), -app_dict[p]),
        )
        rosters[t] = top12_bat
        # Default 12 for bowling XI: top 12 by appearances, with main bowlers ordered first
        top12_bowl = sorted(
            squad_sorted[:12],
            key=lambda p: (-team_bowl_app[t].get(p, 0), bowlers_econ.get(p, 9.5), p),
        )
        bowl_rosters[t] = top12_bowl

    return {
        "batters": batters_sr,
        "batters_bpd": batters_bpd,
        "batters_avg": batters_avg,
        "bowlers_econ": bowlers_econ,
        "bowlers_wkt": bowlers_wkt,
        "bowlers_balls": bowlers_balls_map,
        "team_squads": team_squads,
        "rosters": rosters,
        "bowl_rosters": bowl_rosters,
    }

